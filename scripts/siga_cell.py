#!/usr/bin/env python3
"""Write one SIGA cell's Claude Code configuration for use inside YOUR OWN isolated container.

The supported way to run a cell is the benchmark sandbox, which needs no container:

    benchmarks/siga-geos/bin/siga-bench run --agent siga --cell S+X+M --model MODEL --task ExampleMandel --out DIR

Use this script only if you must run Claude Code in a container you manage. The generated
`run.sh` itself is NOT sandboxed. The container must contain ONLY:

  /plugins/siga    a copy of plugin/ (or plugin_evolving/v3/ for SE): never the repository,
                   whose benchmarks/siga-geos/tasks/*/tests/ and solution/ dirs hold the answers
  /geos_lib        the task's filtered GEOS tree (`siga-bench tree --task T`)
  /workspace       empty and writable
  /cell            this script's output dir

`run.sh` refuses to start if /geos_lib is missing or if any of the task's reference decks, or
any benchmark task/reference/solution directory, is visible anywhere in the container.
Network isolation is up to you: allow only the model gateway (and, for R, the embedding API).

    python scripts/siga_cell.py --cell S+X+M --task ExampleMandel --model MODEL --out /tmp/cell-sxm
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "benchmarks" / "siga-geos"))
from siga_bench import cells, config  # noqa: E402
from siga_bench.cells import parse_cell, system_prompt, task_spec, user_prompt  # noqa: E402,F401

GUARD = r'''# Refuse to run where the answers are visible (see scripts/siga_cell.py).
[[ -d /geos_lib ]] || { echo "run.sh: /geos_lib is missing" >&2; exit 3; }
case "$CLAUDE_PLUGIN_ROOT" in /plugins/*) ;; *) echo "run.sh: plugin root must be under /plugins" >&2; exit 3;; esac
hit=$(find / -xdev \( -path /proc -o -path /sys -o -path /dev -o -path /workspace \) -prune -o \
      \( {names} -o -path '*/tests/reference' -o -path '*/solution/inputs' -o -name siga-geos \) -print -quit 2>/dev/null)
if [[ -n $hit ]]; then
  echo "run.sh: refusing to start: benchmark answers are visible at $hit" >&2
  echo "run.sh: mount only plugin/ at /plugins/siga, never the repository" >&2
  exit 3
fi
'''


def build(cell_name: str, task: str, model: str, out: Path, plugin_root: str = cells.CONTAINER_PLUGIN_ROOT,
          vector_db: str = cells.CONTAINER_VECTOR_DB, paper_tools: bool = False) -> Path:
    if not plugin_root.startswith("/plugins/"):
        raise SystemExit("--plugin-root must be a container path under /plugins/ (mount only the adapter dir there)")
    cell = parse_cell(cell_name)
    task_dir = config.task_dir(task)
    out.mkdir(parents=True, exist_ok=True)
    (out / "system_prompt.md").write_text(system_prompt(cell))
    (out / "prompt.md").write_text(user_prompt(cell, task_spec(task_dir)))
    mcp, settings, env = cells.claude_config(cell, task_dir, plugin_root, vector_db)
    if mcp is not None:
        (out / "mcp.json").write_text(json.dumps(mcp, indent=2, sort_keys=True))
        (out / "settings.json").write_text(json.dumps(settings, indent=2, sort_keys=True))
    flags = cells.claude_flags(cell, "/cell/mcp.json", "/cell/settings.json", paper_tools)
    names = " -o ".join(f"-name {shlex.quote(n)}" for n in cells.reference_basenames(task_dir))
    env_lines = "".join(f"export {k}={shlex.quote(v)}\n" for k, v in sorted(env.items()))
    if "CLAUDE_PLUGIN_ROOT" not in env:
        env_lines += f"export CLAUDE_PLUGIN_ROOT={shlex.quote(plugin_root)}\n"
    run = f"""#!/bin/bash
# SIGA cell {cell_name!r} on task {task_dir.name}, generated by scripts/siga_cell.py.
# NOT SANDBOXED: run only inside an isolated container laid out as described in
# scripts/siga_cell.py (this dir at /cell, plugin/ only at {plugin_root}).
# The paper used a 1500 s timeout per run: `timeout 1500 bash /cell/run.sh`.
set -euo pipefail
{env_lines}{GUARD.replace('{names}', names)}mkdir -p /workspace/inputs
cd /workspace
exec claude -p --verbose --model {shlex.quote(model)} \\
    --append-system-prompt "$(cat /cell/system_prompt.md)" \\
    {' '.join(shlex.quote(f) for f in flags)} \\
    -- "$(cat /cell/prompt.md)"
"""
    (out / "run.sh").write_text(run)
    (out / "run.sh").chmod(0o755)
    (out / "cell.json").write_text(json.dumps({
        "cell": cell_name, "task": task_dir.name, "model": model,
        "components": {k: cell[k] for k in "RSXM"}, "plugin_root": plugin_root if cell["plugin_enabled"] else None,
        "adapter_dir_to_mount": str(cell["plugin_dir"].relative_to(REPO)),
        "primer": str(cell["primer"].relative_to(REPO)),
        "cheatsheet": str(cell["cheatsheet"].relative_to(REPO)) if cell["cheatsheet"] else None,
        "prompt_prefix": cell["prefix"], "disallowed_tools": list(cells.disallowed_tools(paper_tools)),
        "env": env}, indent=1))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cell", required=True)
    ap.add_argument("--task", required=True, help="SIGA task name or id (see `siga-bench tasks`)")
    ap.add_argument("--model", required=True)
    ap.add_argument("--out", required=True, type=Path, help="output dir; keep it outside the repository")
    ap.add_argument("--plugin-root", default=cells.CONTAINER_PLUGIN_ROOT,
                    help="container mount point of the adapter dir (default /plugins/siga)")
    ap.add_argument("--vector-db", default=cells.CONTAINER_VECTOR_DB, help="container path of the R database")
    ap.add_argument("--paper-tools", action="store_true",
                    help="disallow only Skill and AskUserQuestion, as in the paper (web tools stay on)")
    a = ap.parse_args(argv)
    if a.out.resolve().is_relative_to(REPO):
        raise SystemExit("--out must be outside the repository")
    out = build(a.cell, a.task, a.model, a.out, a.plugin_root, a.vector_db, a.paper_tools)
    print(f"{out}/run.sh   (copy {json.loads((out / 'cell.json').read_text())['adapter_dir_to_mount']}/ "
          f"to {a.plugin_root} in the container; mount this dir at /cell)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
